    fn lookup_and_fill() {
        assert_eq!(lookup_en("Salvar"), Some("Save"));
        assert_eq!(lookup_en("texto inexistente"), None);
        assert_eq!(fill("Criados: {}", &[&"a, b"]), "Criados: a, b");
        assert_eq!(fill("{} de {}", &[&1, &2]), "1 de 2");
        assert_eq!(fill("sem marcador", &[&1]), "sem marcador");
        assert_eq!(fill("{} e {}", &[&"x"]), "x e {}");
    }

