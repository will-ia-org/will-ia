//! Internacionalização mínima da UI (sem crates externas).
//!
//! Convenção do projeto: os textos de UI no código ficam em **pt-BR** e são a
//! própria chave de tradução. Uma tabela estática mapeia cada texto para o
//! inglês; quando a chave não existe na tabela, o pt-BR é devolvido tal qual.
//!
//! API:
//!
//! - [`set_language`] / [`language`]: idioma corrente, global ao processo
//!   (`settings.general.language`, `"pt-BR"` ou `"en"`). O app chama
//!   `set_language` a cada quadro a partir do snapshot das configurações, então
//!   salvar a seção Geral troca a UI inteira no quadro seguinte.
//! - [`tr`]: texto fixo. `ui.button(tr("Salvar"))`,
//!   `ui::field(ui, tr("Rótulo"), Some(tr("dica")), ..)`. Devolve `&'static str`,
//!   então serve onde se espera `&str` e vira `String` com `.to_string()`.
//! - [`trf`]: texto com valores em tempo de execução. O modelo em pt-BR usa
//!   marcadores `{}` (só a forma simples, sem `:.4` nem nomes); cada `{}` é
//!   substituído, em ordem, pelo `Display` do argumento correspondente:
//!   `trf("Criados: {}", &[&list])`, `trf("{} de {} servidor(es)", &[&a, &b])`.
//!   Para precisão/formatação, formate antes: `trf("US$ {}", &[&format!("{v:.4}")])`.
//!   Marcadores a mais ficam literais; argumentos a mais são ignorados.
//!
//! Em cada página: `use crate::i18n::{tr, trf};`.
//!
//! Para adicionar um texto: envolva o literal pt-BR com `tr`/`trf` e acrescente
//! o par `(pt, en)` em [`TABLE`]. Chaves duplicadas são rejeitadas pelo teste
//! `table_has_no_duplicate_keys`.

use std::collections::HashMap;
use std::fmt::Display;
use std::sync::atomic::{AtomicU8, Ordering};
use std::sync::OnceLock;

/// Idiomas suportados pela UI.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    PtBr = 0,
    En = 1,
}

impl Lang {
    /// `"en"`, `"en-US"`, `"en_GB"`… → `En`; qualquer outra coisa → `PtBr`.
    pub fn from_code(code: &str) -> Lang {
        let c = code.trim().to_ascii_lowercase();
        if c == "en" || c.starts_with("en-") || c.starts_with("en_") {
            Lang::En
        } else {
            Lang::PtBr
        }
    }
}

static LANG: AtomicU8 = AtomicU8::new(Lang::PtBr as u8);

/// Define o idioma corrente da UI (barato; pode ser chamado a cada quadro).
pub fn set_language(code: &str) {
    LANG.store(Lang::from_code(code) as u8, Ordering::Relaxed);
}

/// Idioma corrente da UI.
pub fn language() -> Lang {
    match LANG.load(Ordering::Relaxed) {
        1 => Lang::En,
        _ => Lang::PtBr,
    }
}

/// Traduz um texto fixo. A chave é o próprio texto em pt-BR; sem tradução,
/// devolve a chave.
pub fn tr(pt: &'static str) -> &'static str {
    match language() {
        Lang::PtBr => pt,
        Lang::En => lookup_en(pt).unwrap_or(pt),
    }
}

/// Traduz um modelo com marcadores `{}` e preenche com `args`, em ordem.
/// Ver a documentação do módulo.
pub fn trf(pt: &'static str, args: &[&dyn Display]) -> String {
    fill(tr(pt), args)
}

/// Tradução para inglês de uma chave pt-BR, se existir (independe do idioma
/// corrente; útil em testes).
pub fn lookup_en(pt: &str) -> Option<&'static str> {
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| TABLE.iter().copied().collect())
        .get(pt)
        .copied()
}

fn fill(template: &str, args: &[&dyn Display]) -> String {
    let mut out = String::with_capacity(template.len() + 16);
    let mut args = args.iter();
    let mut rest = template;
    while let Some(i) = rest.find("{}") {
        out.push_str(&rest[..i]);
        match args.next() {
            Some(a) => out.push_str(&a.to_string()),
            None => out.push_str("{}"),
        }
        rest = &rest[i + 2..];
    }
    out.push_str(rest);
    out
}

